function superscript(n: number): string {
  return String(n).split('').map(d => '⁰¹²³⁴⁵⁶⁷⁸⁹'[Number(d)]).join('');
}

function buildConfig(z: number, symbol: string): string {
  const ex = EXCEPTIONS[symbol];
  const raw = ex ?? (() => {
    let left = z;
    const filled: string[] = [];
    for (const [n, l] of ORDER) {
      if (left <= 0) break;
      const k = Math.min(CAP[l], left);
      filled.push(`${n}${l}${k}`);
      left -= k;
    }
    // Compress with a noble-gas core.
    const core = NOBLE.find(([nz]) => nz < z);
    if (!core) return filled.join(' ');
    let skipped = 0, i = 0;
    while (i < filled.length && skipped < core[0]) {
      skipped += Number(filled[i].slice(2));
      i++;
    }
    const rest = filled.slice(i).sort((a, b) => {
      const key = (s: string) => Number(s[0]) * 10 + 'spdf'.indexOf(s[1]);
      return key(a) - key(b);
    });
    return `[${core[1]}] ${rest.join(' ')}`;
  })();
  // Pretty-print exponents as superscripts.
  return raw.replace(/([spdf])(\d+)/g, (_, l: string, k: string) => `${l}${superscript(Number(k))}`);
}

// ── Grid position (18-column table, with f-block rows below) ────────────────
function layout(z: number): { group: number | null; period: number } {
  if (z === 1) return { group: 1, period: 1 };
  if (z === 2) return { group: 18, period: 1 };
  if (z <= 4) return { group: z - 2, period: 2 };
  if (z <= 10) return { group: z + 8, period: 2 };
  if (z <= 12) return { group: z - 10, period: 3 };
  if (z <= 18) return { group: z, period: 3 };
  if (z <= 36) return { group: z - 18, period: 4 };
  if (z <= 54) return { group: z - 36, period: 5 };
  if (z <= 56) return { group: z - 54, period: 6 };
  if (z <= 71) return { group: null, period: 6 }; // La–Lu
  if (z <= 86) return { group: z - 68, period: 6 };
  if (z <= 88) return { group: z - 86, period: 7 };
  if (z <= 103) return { group: null, period: 7 }; // Ac–Lr
  return { group: z - 100, period: 7 };
}

