  comp[s.B.symbol] = (comp[s.B.symbol] ?? 0) + 1;
  comp[s.X.symbol] = (comp[s.X.symbol] ?? 0) + anions;

  const rA = RADII_A_XII[key(s.A.symbol, s.A.charge)] ?? null;
  const rB = RADII_B_VI[key(s.B.symbol, s.B.charge)] ?? null;
